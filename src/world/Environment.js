import * as THREE from 'three';
import { CONFIG } from '../data/config.js';
import { GeoBatch, meshesFromMerged } from '../utils/GeoBatch.js';
import { rand } from '../utils/math.js';
import { makeRoadMaps, makeGrassTexture, makeVergeTexture } from '../utils/textures.js';
import { registerNight } from '../utils/nightLights.js';
import { envHolder } from '../utils/envMap.js';
import { bendOffset } from '../utils/bend.js';
import { ZonePlanner, ZONES, fillSegment, prewarmScenery, ELEVATION } from './Scenery.js';
import { damp } from '../utils/math.js';

// =============================================================
// Environment - everything that is NOT gameplay:
// sky (sun, moon, stars, clouds), ground, the road itself, kerbs
// and the endless roadside generated by Scenery in 40 m segments.
//
// THE ENDLESS ROAD TRICK
// The player never really moves forward. Instead:
//  * road + ground textures slide towards the camera (texture offset)
//  * roadside segments move towards the camera; when one passes
//    behind us it jumps to the far end and is REFILLED for the zone
//    (countryside, town, city...) at that point of the road.
// Curves come from utils/bend.js, so everything here bends for free.
// =============================================================

const ROAD_TILE = 12; // metres covered by one copy of the road texture
const ROAD_LENGTH = 520;
const ROAD_NEAR_Z = 110;
const GROUND_SIZE = 2400;
const GROUND_TILE = 12;
const SEG_LEN = 40;
const SEG_COUNT = 12;
const SEG_RECYCLE_Z = 80;
const STREET_LIGHTS = 4; // real lights, re-assigned to the nearest lamps each frame

const SKY_VERTEX = /* glsl */ `
  varying vec3 vDir;
  void main() {
    vDir = position;
    gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
  }
`;

const SKY_FRAGMENT = /* glsl */ `
  uniform vec3 topColor;
  uniform vec3 midColor;
  uniform vec3 horizonColor;
  uniform vec3 sunColor;
  uniform vec3 cloudColor;
  uniform vec3 sunDir;
  uniform vec3 moonDir;
  uniform float starStrength;
  uniform float cloudiness;
  uniform float time;
  varying vec3 vDir;

  float hash(vec3 p) {
    p = fract(p * 0.3183099 + 0.1);
    p *= 17.0;
    return fract(p.x * p.y * p.z * (p.x + p.y + p.z));
  }
  float noise(vec2 p) {
    vec2 i = floor(p);
    vec2 f = fract(p);
    f = f * f * (3.0 - 2.0 * f);
    float a = hash(vec3(i, 0.0));
    float b = hash(vec3(i + vec2(1.0, 0.0), 0.0));
    float c = hash(vec3(i + vec2(0.0, 1.0), 0.0));
    float d = hash(vec3(i + vec2(1.0, 1.0), 0.0));
    return mix(mix(a, b, f.x), mix(c, d, f.x), f.y);
  }
  float fbm(vec2 p) {
    float v = 0.0;
    float a = 0.5;
    for (int i = 0; i < 5; i++) { v += a * noise(p); p *= 2.03; a *= 0.5; }
    return v;
  }

  void main() {
    vec3 d = normalize(vDir);
    float h = d.y;
    vec3 col = mix(horizonColor, midColor, smoothstep(0.0, 0.25, h));
    col = mix(col, topColor, smoothstep(0.25, 0.85, h));
    if (h < 0.0) col = horizonColor;

    // sun: soft glow + disc
    float sd = max(dot(d, sunDir), 0.0);
    col += sunColor * pow(sd, 10.0) * 0.35;
    col += sunColor * smoothstep(0.9993, 0.9996, sd) * 3.0;

    // moon
    float md = max(dot(d, moonDir), 0.0);
    col += vec3(0.9, 0.93, 1.0) * smoothstep(0.99955, 0.99975, md) * 1.4 * starStrength;
    col += vec3(0.35, 0.45, 0.7) * pow(md, 60.0) * 0.2 * starStrength;

    // twinkling stars
    if (h > 0.03) {
      float s = hash(floor(d * 300.0));
      float tw = 0.6 + 0.4 * sin(time * 2.0 + s * 60.0);
      col += vec3(step(0.9975, s)) * starStrength * tw * smoothstep(0.03, 0.25, h);
    }

    // drifting clouds
    if (h > 0.0) {
      vec2 cp = d.xz / (h + 0.12) * 1.4 + vec2(time * 0.008, 0.0);
      float c = fbm(cp);
      float edge = 1.0 - cloudiness * 0.8;
      float cover = smoothstep(edge - 0.2, edge + 0.15, c);
      col = mix(col, cloudColor, cover * smoothstep(0.0, 0.1, h) * (0.4 + cloudiness * 0.55));
    }

    gl_FragColor = vec4(col, 1.0);
    #include <tonemapping_fragment>
    #include <colorspace_fragment>
  }
`;

export class Environment {
  constructor(scene, renderer, structures) {
    this.scene = scene;
    this.structures = structures;
    this.aniso = Math.min(8, renderer.capabilities.getMaxAnisotropy());
    this.zones = new ZonePlanner();
    this.segments = [];
    this.events = [];
    this.odometer = 0;
    this.elevation = 0;
    this.zone = 'countryside';

    this.createSky();
    this.createGround();
    this.createRoad();
    this.createMountains();
    prewarmScenery();
    this.createSegments();
    this.createStreetLights();
  }

  // ---------- Sky ----------
  createSky() {
    this.skyUniforms = {
      topColor: { value: new THREE.Color() },
      midColor: { value: new THREE.Color() },
      horizonColor: { value: new THREE.Color() },
      sunColor: { value: new THREE.Color() },
      cloudColor: { value: new THREE.Color() },
      sunDir: { value: new THREE.Vector3(0, 1, 0) },
      moonDir: { value: new THREE.Vector3(0, -1, 0) },
      starStrength: { value: 0 },
      cloudiness: { value: 0.2 },
      time: { value: 0 },
    };
    this.sky = new THREE.Mesh(
      new THREE.SphereGeometry(1000, 32, 16),
      new THREE.ShaderMaterial({
        uniforms: this.skyUniforms,
        vertexShader: SKY_VERTEX,
        fragmentShader: SKY_FRAGMENT,
        side: THREE.BackSide,
        depthWrite: false,
        fog: false,
      })
    );
    this.sky.renderOrder = -10;
    this.sky.frustumCulled = false;
    this.scene.add(this.sky);
  }

  // ---------- Ground (moves down on flyovers & bridges) ----------
  createGround() {
    this.groundGroup = new THREE.Group();
    this.scene.add(this.groundGroup);

    this.groundTex = makeGrassTexture();
    this.groundTex.repeat.set(GROUND_SIZE / GROUND_TILE, GROUND_SIZE / GROUND_TILE);
    this.groundTex.anisotropy = this.aniso;
    this.groundMat = new THREE.MeshStandardMaterial({ map: this.groundTex, color: ZONES.countryside.ground, roughness: 1 });
    // subdivided along the road so the curve bend (a per-vertex effect) stays smooth
    const ground = new THREE.Mesh(new THREE.PlaneGeometry(GROUND_SIZE, GROUND_SIZE, 16, 240), this.groundMat);
    ground.rotation.x = -Math.PI / 2;
    ground.position.y = -0.08;
    ground.receiveShadow = true;
    this.groundGroup.add(ground);

    // reddish-brown dirt verges just outside the kerbs (very Indian roadside)
    this.vergeTex = makeVergeTexture();
    this.vergeTex.repeat.set(1, ROAD_LENGTH / 8);
    this.vergeTex.anisotropy = this.aniso;
    const dirt = new THREE.MeshStandardMaterial({ map: this.vergeTex, roughness: 1 });
    for (const s of [-1, 1]) {
      const strip = new THREE.Mesh(new THREE.PlaneGeometry(4, ROAD_LENGTH, 1, ROAD_LENGTH / 5), dirt);
      strip.rotation.x = -Math.PI / 2;
      strip.position.set(s * 11.2, -0.06, ROAD_NEAR_Z - ROAD_LENGTH / 2);
      strip.scale.x = s; // mirror so the grassy edge is always on the outside
      strip.receiveShadow = true;
      this.groundGroup.add(strip);
    }
  }

  // ---------- Road surface, deck & kerbs ----------
  createRoad() {
    const W = CONFIG.ROAD_SURFACE_WIDTH;
    // colour + bump (normal) + roughness maps, all scrolled together
    const maps = makeRoadMaps(W, ROAD_TILE, CONFIG.LANES, CONFIG.LANE_DIRECTION, matchMedia('(pointer: coarse)').matches ? 512 : 1024);
    this.roadMaps = [maps.map, maps.normalMap, maps.roughnessMap];
    for (const t of this.roadMaps) {
      t.repeat.set(1, ROAD_LENGTH / ROAD_TILE);
      t.anisotropy = this.aniso;
    }
    this.roadTex = maps.map;
    this.roadMat = new THREE.MeshStandardMaterial({
      map: maps.map, normalMap: maps.normalMap, roughnessMap: maps.roughnessMap,
      normalScale: new THREE.Vector2(0.8, 0.8), roughness: 1, metalness: 0.02,
      envMap: envHolder.map, envMapIntensity: 0,
    });
    const road = new THREE.Mesh(new THREE.PlaneGeometry(W, ROAD_LENGTH, 4, ROAD_LENGTH / 4), this.roadMat);
    road.rotation.x = -Math.PI / 2;
    road.position.set(0, 0.01, ROAD_NEAR_Z - ROAD_LENGTH / 2);
    road.receiveShadow = true;
    this.scene.add(road);

    // concrete deck under the road: hidden underground normally,
    // visible as the bridge structure when the ground drops away
    const deck = new THREE.Mesh(
      new THREE.BoxGeometry(W + 2.4, 1.6, ROAD_LENGTH, 1, 1, ROAD_LENGTH / 5),
      new THREE.MeshStandardMaterial({ color: 0x9c978e, roughness: 0.95 })
    );
    deck.position.set(0, -0.82, ROAD_NEAR_Z - ROAD_LENGTH / 2);
    deck.receiveShadow = true;
    this.scene.add(deck);
  }

  /** Black & white painted kerb stones - one merged mesh per segment. */
  kerbGeometry() {
    if (!this.kerbMerged) {
      const b = new GeoBatch();
      const x = CONFIG.ROAD_SURFACE_WIDTH / 2 + 0.25;
      for (const s of [-1, 1]) {
        for (let i = 0; i < SEG_LEN; i++) {
          b.add('kerb', new THREE.BoxGeometry(0.5, 0.25, 0.98), {
            pos: [s * x, 0.125, -SEG_LEN / 2 + i + 0.5], color: i % 2 ? 0x1c1c1c : 0xf0f0f0,
          });
        }
      }
      // cat's eyes: small reflective road studs on the lane lines every 10 m
      const L = CONFIG.LANES;
      for (let i = 0; i < L.length - 1; i++) {
        const x = (L[i] + L[i + 1]) / 2;
        const centre = CONFIG.LANE_DIRECTION[i] !== CONFIG.LANE_DIRECTION[i + 1];
        for (let z = -SEG_LEN / 2 + 3; z < SEG_LEN / 2; z += 10) {
          b.add(centre ? 'studAmber' : 'stud', new THREE.BoxGeometry(0.14, 0.035, 0.1), { pos: [x, 0.03, z] });
        }
      }
      for (const s of [-1, 1]) {
        for (let z = -SEG_LEN / 2 + 8; z < SEG_LEN / 2; z += 10) {
          b.add('studRed', new THREE.BoxGeometry(0.12, 0.035, 0.1), { pos: [s * (L[L.length - 1] + 1.65), 0.03, z] });
        }
      }
      this.kerbMerged = b.merge();
      const stud = (color) => registerNight(new THREE.MeshStandardMaterial({
        color: 0xdddddd, emissive: color, emissiveIntensity: 0.1, roughness: 0.3,
      }), 'emissiveIntensity', 0.1, 1.1);
      this.kerbMat = {
        kerb: new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 0.7 }),
        stud: stud(0xf4f8ff),
        studAmber: stud(0xffb000),
        studRed: stud(0xff2020),
      };
    }
    return meshesFromMerged(this.kerbMerged, this.kerbMat, { receiveShadow: true });
  }

  createMountains() {
    this.mountainMat = new THREE.MeshStandardMaterial({ color: 0x6a7080, flatShading: true, fog: false, roughness: 1 });
    const b = new GeoBatch();
    for (let x = -1000; x < 1000; x += rand(70, 130)) {
      const dip = 0.5 + 0.5 * Math.min(1, Math.abs(x) / 300); // lower behind the road
      const h = rand(50, 110) * dip;
      b.add('m', new THREE.ConeGeometry(rand(90, 170), h, 5), {
        pos: [x, h / 2 - 3, rand(-820, -700)], rot: [0, rand(0, Math.PI), 0], color: 0xffffff,
      });
    }
    this.mountains = meshesFromMerged(b.merge(), { m: this.mountainMat });
    this.scene.add(this.mountains);
  }

  setMountainColor(color) {
    this.mountainMat.color.copy(color);
  }

  // ---------- Segments ----------
  createSegments() {
    for (let i = 0; i < SEG_COUNT; i++) {
      const seg = new THREE.Group();
      seg.add(this.kerbGeometry());
      const content = new THREE.Group();
      seg.add(content);
      seg.userData.content = content;
      seg.position.z = SEG_RECYCLE_Z - SEG_LEN / 2 - i * SEG_LEN;
      this.refill(seg);
      this.segments.push(seg);
      this.scene.add(seg);
    }
  }

  /** Fills a segment for the zone at its position on the road. */
  refill(seg) {
    const roadDist = this.odometer - seg.position.z;
    const section = this.structures.sectionAt(roadDist, 30);
    const zone = this.zones.zoneAt(roadDist).zone;
    const content = seg.userData.content;
    let info;
    if (section) {
      // elevated: drop the scenery below the deck; rivers under bridges
      info = fillSegment(content, zone, { river: section.type === 'river' });
      content.position.y = -ELEVATION;
    } else if (this.structures.sectionAt(roadDist, 90)) {
      // ramps next to elevated sections stay empty, so nothing floats in the air
      info = fillSegment(content, zone, { empty: true });
      content.position.y = 0;
    } else {
      info = fillSegment(content, zone);
      content.position.y = 0;
    }
    seg.userData.lamps = section ? [] : info.lamps;
    if (info.petrol && !section) {
      this.events.push({ type: 'petrol', side: info.petrol.side, z: seg.position.z + info.petrol.z });
    }
  }

  // ---------- Street lights (a few real lights reused) ----------
  createStreetLights() {
    this.streetLights = [];
    for (let i = 0; i < STREET_LIGHTS; i++) {
      const l = new THREE.PointLight(0xffc580, 0, 26, 1.6);
      this.scene.add(l);
      this.streetLights.push(l);
    }
  }

  updateStreetLights(lampFactor) {
    const candidates = [];
    if (lampFactor > 0.05) {
      for (const seg of this.segments) {
        for (const p of seg.userData.lamps || []) {
          const z = seg.position.z + p[2];
          if (z > -75 && z < 18) candidates.push({ x: p[0], y: p[1] + seg.userData.content.position.y, z });
        }
      }
      candidates.sort((a, b) => Math.abs(a.z + 14) - Math.abs(b.z + 14));
    }
    const off = { x: 0, y: 0 };
    this.streetLights.forEach((light, i) => {
      const c = candidates[i];
      if (!c) {
        light.intensity = 0;
        return;
      }
      bendOffset(c.z, off);
      light.position.set(c.x + off.x, c.y + off.y, c.z);
      light.intensity = 38 * lampFactor;
    });
  }

  setWetness(w) {
    this.roadMat.roughness = 1 - w * 0.72; // multiplies the roughness map
    this.roadMat.metalness = 0.02 + w * 0.2;
    this.roadMat.envMapIntensity = w * 0.9;
    this.roadMat.normalScale.setScalar(0.8 - w * 0.45); // puddles smooth the surface
    this.roadMat.color.setScalar(1 - w * 0.35);
  }

  get zoneLabel() {
    return ZONES[this.zone].label;
  }

  // ---------- Per-frame update ----------
  update(dt, speed, odometer, camera, lampFactor) {
    const ds = speed * dt; // metres travelled this frame
    this.odometer = odometer;

    // slide the textures (offset is measured in texture repeats)
    const roadOffset = (this.roadTex.offset.y + ds / ROAD_TILE) % 1;
    for (const t of this.roadMaps) t.offset.y = roadOffset;
    this.groundTex.offset.y = (this.groundTex.offset.y + ds / GROUND_TILE) % 1;
    this.vergeTex.offset.y = (this.vergeTex.offset.y + ds / 8) % 1;

    for (const seg of this.segments) {
      seg.position.z += ds;
      if (seg.position.z - SEG_LEN / 2 > SEG_RECYCLE_Z) {
        seg.position.z -= SEG_LEN * SEG_COUNT;
        this.refill(seg);
      }
    }

    // ground drops away on flyovers / bridges
    const elevated = this.structures.sectionAt(odometer + 15);
    this.elevation = damp(this.elevation, elevated ? ELEVATION : 0, 2.2, dt);
    this.groundGroup.position.y = -this.elevation;

    // zone colour of the ground, blended smoothly
    this.zone = this.zones.zoneAt(odometer).zone;
    const tint = new THREE.Color(ZONES[this.zone].ground);
    this.groundMat.color.lerp(tint, 1 - Math.exp(-dt * 0.8));

    this.sky.position.copy(camera.position);
    this.skyUniforms.time.value += dt;
    this.updateStreetLights(lampFactor);
  }
}




